"""Regenerate worlds/maze.wbt and its textures from agent/maze.py:  python webots/make_world.py"""
import math
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from agent.maze import (CELL, LABEL_H, LABEL_W, LANDMARKS, SIGN_Z, WALL_H, build,
                        floor_label_image, sign_image)
from backends.webots_backend import (OVERHEAD_CAMERA_FOV, OVERHEAD_IMAGE_PX, overhead_camera_height,
                                     overhead_span_m)

ROUTE_TEX = "route"
LABEL_TEX = "labels"
LABEL_Z = 0.001
LOOK_DOWN_NORTH_UP = "-0.5774 0.5774 0.5774 2.0944"

HERE = Path(__file__).parent
WORLD = HERE / "worlds" / "maze.wbt"
TEX = HERE / "worlds" / "textures"
PROTO = "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects"


def make_textures(lay):
    TEX.mkdir(parents=True, exist_ok=True)
    keep = {f"{name.lower()}.png" for name, _ in LANDMARKS.values()}
    for old in TEX.glob("*.png"):
        if old.name not in keep:
            old.unlink()
    shutil.rmtree(TEX / "direction", ignore_errors=True)
    for name, colour in LANDMARKS.values():
        sign_image(name, colour).save(TEX / f"{name.lower()}.png")
    (TEX / ROUTE_TEX).mkdir(exist_ok=True)
    for old in (TEX / ROUTE_TEX).glob("*.png"):
        old.unlink()
    for s in lay.route_signs:
        s.image().resize((1024, 512)).save(TEX / ROUTE_TEX / f"{s.id}.png")
    (TEX / LABEL_TEX).mkdir(exist_ok=True)
    for old in (TEX / LABEL_TEX).glob("*.png"):
        old.unlink()
    for name in lay.towns:
        floor_label_image(name).resize((1024, 256)).save(TEX / LABEL_TEX / f"{label_file(name)}.png")


def label_file(name: str) -> str:
    return name.lower().replace(" ", "_")


def label_node(lay, name: str) -> str:
    x, y = lay.label_centre(name)
    return f"""Pose {{
  translation {x:.4f} {y:.4f} {LABEL_Z}
  children [ Shape {{
    appearance PBRAppearance {{ baseColorMap ImageTexture {{ url [ "textures/{LABEL_TEX}/{label_file(name)}.png" ] }}
                               roughness 1 metalness 0 }}
    geometry Plane {{ size {LABEL_W} {LABEL_H} }} }} ]
}}"""


def overhead_camera_node(lay) -> str:
    height = overhead_camera_height(overhead_span_m(lay))
    return f"""Robot {{
  translation 0 0 {height:.4f}
  rotation {LOOK_DOWN_NORTH_UP}
  children [ Camera {{ name "overhead" width {OVERHEAD_IMAGE_PX} height {OVERHEAD_IMAGE_PX} fieldOfView {OVERHEAD_CAMERA_FOV} far 10 }} ]
  name "overhead camera"
  controller "overhead_camera"
}}"""


def sign_node(s, url: str) -> str:
    phi = math.radians(s.facing_deg + 90)
    return f"""Pose {{
  translation {s.x:.4f} {s.y:.4f} {SIGN_Z}
  rotation 0 0 1 {phi:.4f}
  children [ Pose {{ rotation 1 0 0 1.5708 children [ Shape {{
    appearance PBRAppearance {{ baseColorMap ImageTexture {{ url [ "{url}" ] }}
                               roughness 1 metalness 0 }}
    geometry Plane {{ size {s.w} {s.h} }} }} ] }} ]
}}"""


def main():
    lay = build()
    parts = []
    for i, (x, y, sx, sy) in enumerate(lay.wall_boxes(), 1):
        size = f"{sx:.4f} {sy:.4f} {WALL_H}"
        parts.append(f"""Solid {{
  translation {x:.4f} {y:.4f} {WALL_H / 2}
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.93 0.93 0.9 roughness 1 metalness 0 }}
                     geometry Box {{ size {size} }} }} ]
  name "wall{i}"
  boundingObject Box {{ size {size} }}
}}""")
    for s in lay.signs:
        parts.append(sign_node(s, f"textures/{s.name.lower()}.png"))
    for s in lay.route_signs:
        parts.append(sign_node(s, f"textures/{ROUTE_TEX}/{s.id}.png"))
    for name in lay.towns:
        parts.append(label_node(lay, name))
    parts.append(overhead_camera_node(lay))

    size = max(lay.rows, lay.cols) * CELL + 0.3
    sx, sy, heading = lay.start
    world = f"""#VRML_SIM R2025a utf8

EXTERNPROTO "{PROTO}/objects/floors/protos/RectangleArena.proto"
EXTERNPROTO "{PROTO}/robots/gctronic/e-puck/protos/E-puck.proto"

WorldInfo {{
  info [ "Gemini Robotics ER 2 maze rover - generated by make_world.py" ]
  basicTimeStep 16
}}
Viewpoint {{
  orientation -0.5774 0.5774 0.5774 2.0944
  position 0 0 {size * 1.6:.2f}
}}
Background {{ skyColor [ 0.8 0.8 0.82 ] }}
DirectionalLight {{ direction 0.3 0.4 -1 intensity 1.2 ambientIntensity 0.6 castShadows FALSE }}
RectangleArena {{
  floorSize {size:.2f} {size:.2f}
  floorTileSize {CELL * 2} {CELL * 2}
  floorAppearance PBRAppearance {{ baseColor 0.4 0.4 0.42 roughness 1 metalness 0 }}
  wallHeight 0.03
}}
E-puck {{
  translation {sx:.4f} {sy:.4f} 0
  rotation 0 0 1 {math.radians(heading):.4f}
  controller "rover_agent"
  supervisor TRUE
  camera_width 320
  camera_height 240
  camera_fieldOfView 1.4
}}
""" + "\n".join(parts) + "\n"
    WORLD.parent.mkdir(parents=True, exist_ok=True)
    WORLD.write_text(world)
    make_textures(lay)
    print(f"Wrote {WORLD} ({len(lay.wall_boxes())} walls, {len(lay.signs)} landmark signs, "
          f"{len(lay.route_signs)} road signs, {len(lay.towns)} floor labels, overhead camera)")


if __name__ == "__main__":
    main()
